from __future__ import annotations
from pathlib import Path
from typing import Any
import numpy as np

PQR_ATOM_LINE_FMT = "ATOM %6d %3s  UNL A   1      %6.3f  %6.3f  %6.3f %7.4f %6.2f\n"
REMARK_HEADER = "REMARK   1 PQR file generated by autoAPBS version 1 0 0\n"
REMARK_BLANK = "REMARK   1\n"
REMARK_MOL_FMT = "REMARK   1 MOLECULE: %s\n"
PQR_END = "TER\nEND\n"


def nsplit(s, delim=None):
    return [x for x in s.split(delim) if x]


class POINT:
    def __init__(self, x, y, z):
        self.x = x
        self.y = y
        self.z = z


class MOLECULE:
    def __init__(self, random_state: int | None = 42):
        self.name: str = ""
        self.coord: list[POINT] = []
        self.atomtype: list[str] = []
        self.charge: list[float] = []
        self.radius: list[float] = []
        self.axis: Any = []
        self.theta: float = 0.0
        self.dtheta: float = 0.0
        self.rnd_rot: bool = False
        self.uni_rot: bool = False
        self._rng = np.random.default_rng(random_state)

    _LEGACY_ALIASES = {
        "getNatoms": "get_natoms",
        "randomRotation": "random_rotation",
        "uniformRotation": "uniform_rotation",
        "nextRotation": "next_rotation",
    }

    def __getattr__(self, name: str):
        if name in self._LEGACY_ALIASES:
            return getattr(self, self._LEGACY_ALIASES[name])
        raise AttributeError(f"'{type(self).__name__}' object has no attribute '{name}'")

    def get_natoms(self):
        return len(self.coord)

    def rotate(self, vec, axis_, angle_):
        """Rodrigues rotation formula"""
        axis_arr = np.array(axis_)
        vec_arr = np.array(vec)
        axis_norm = axis_arr / np.linalg.norm(axis_arr)
        term1 = vec_arr * np.cos(angle_)
        term2 = (np.cross(axis_norm, vec_arr)) * np.sin(angle_)
        term3 = axis_norm * ((1 - np.cos(angle_)) * axis_norm.dot(vec_arr))
        return term1 + term2 + term3

    def random_rotation(self):
        self.rnd_rot = True
        self.uni_rot = False

    def uniform_rotation(self, nrot=100.0):
        self.rnd_rot = False
        self.uni_rot = True
        self.axis = self._rng.standard_normal((3,))
        self.axis /= np.linalg.norm(self.axis)
        self.theta = 0.0
        self.dtheta = 2 * np.pi / float(nrot)

    def next_rotation(self):
        if self.rnd_rot:
            self.axis = self._rng.standard_normal((3,))
            self.axis /= np.linalg.norm(self.axis)
            self.theta = float(self._rng.uniform(0, 2 * np.pi))
        else:
            self.theta += self.dtheta

        for i in range(self.get_natoms()):
            vec = [self.coord[i].x, self.coord[i].y, self.coord[i].z]
            self.coord[i].x, self.coord[i].y, self.coord[i].z = self.rotate(
                vec, self.axis, self.theta
            )


def get_vdw_radius(asymbl_):
    vdw_table = {
        "h": 1.20,
        "f": 1.47,
        "cl": 1.75,
        "br": 1.85,
        "i": 1.98,
        "o": 1.52,
        "n": 1.55,
        "c": 1.70,
        "p": 1.80,
        "s": 1.80,
    }
    asymbl = asymbl_.lower()
    if asymbl in vdw_table:
        return vdw_table[asymbl]
    print("Error! VDW radis not found [%s]" % (asymbl_))
    return 9.99


getVDWRadius = get_vdw_radius


def acread(acin):
    m = MOLECULE()
    m.name = Path(acin).resolve().stem
    with open(acin) as fi:
        for line in fi:
            if "ATOM" in line:
                v = nsplit(line.strip(), " ")
                m.coord.append(POINT(float(v[5]), float(v[6]), float(v[7])))
                m.atomtype.append(v[2])
                m.charge.append(float(v[8]))
                m.radius.append(get_vdw_radius(v[2]))
    return m


def writepqr(m, pqrout):
    with open(pqrout, "w") as fo:
        fo.write(REMARK_HEADER)
        fo.write(REMARK_BLANK)
        fo.write(REMARK_MOL_FMT % (pqrout.split(".")[0]))
        fo.write(REMARK_BLANK)
        for i in range(m.get_natoms()):
            fo.write(
                PQR_ATOM_LINE_FMT
                % (
                    int(i + 1),
                    m.atomtype[i],
                    m.coord[i].x,
                    m.coord[i].y,
                    m.coord[i].z,
                    m.charge[i],
                    m.radius[i],
                )
            )
        fo.write(PQR_END)


def ac2pqr(acin, pqrout):
    with open(acin) as fi, open(pqrout, "w") as fo:
        fo.write(REMARK_HEADER)
        fo.write(REMARK_BLANK)
        fo.write(REMARK_MOL_FMT % (acin.split(".")[0]))
        fo.write(REMARK_BLANK)
        for line in fi:
            if "ATOM" in line:
                v = nsplit(line.strip(), " ")
                fo.write(
                    PQR_ATOM_LINE_FMT
                    % (
                        int(v[1]),
                        v[2],
                        float(v[5]),
                        float(v[6]),
                        float(v[7]),
                        float(v[8]),
                        float(get_vdw_radius(v[2])),
                    )
                )
        fo.write(PQR_END)


def mpdb2pqr(mpdbin, pqrout):
    with open(mpdbin) as fi, open(pqrout, "w") as fo:
        fo.write(REMARK_HEADER)
        fo.write(REMARK_BLANK)
        fo.write(REMARK_MOL_FMT % (mpdbin.split(".")[0]))
        fo.write(REMARK_BLANK)
        for line in fi:
            if "ATOM" in line:
                v = nsplit(line.strip(), " ")
                fo.write(
                    PQR_ATOM_LINE_FMT
                    % (
                        int(v[1]),
                        v[2],
                        float(v[5]),
                        float(v[6]),
                        float(v[7]),
                        float(v[8]),
                        float(v[9]),
                    )
                )
        fo.write(PQR_END)
